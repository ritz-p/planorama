'use strict';
const fs = require('node:fs');
const crypto = require('node:crypto');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8').replace(/\r\n/g, '\n');
const inventory = JSON.parse(read('tests/fixtures/aws-inventory/6.70.0.json'));
const decisions = JSON.parse(read('docs/aws-semantic-decisions.json'));
const evidenceFile = 'docs/aws-semantic-evidence.json';
function extract(block, prefix = '', result = []) {
 for (const [name, attr] of Object.entries(block.attributes || {})) {
  if (attr.sensitive || attr.write_only) continue;
  const field = prefix + name;
  if ((attr.optional || attr.required) && !attr.sensitive && !attr.write_only && /(?:^|_)(?:arn|arns|id|ids|name|names|subnets|security_groups|role|bucket|source|target)$/.test(name) && !['id','arn','name','tags','tags_all','description'].includes(name)) result.push(field);
  if (attr.nested_type) extract(attr.nested_type, field + '.', result);
 }
 for (const [name, child] of Object.entries(block.block_types || {})) extract(child.block, prefix + name + '.', result);
 return result.sort();
}
function buildEvidence(schemaBytes) {
 const hash = crypto.createHash('sha256').update(schemaBytes).digest('hex');
 if (hash !== inventory.schemaSha256) throw Error('Pinned schema SHA-256 mismatch');
 const schema = JSON.parse(schemaBytes).provider_schemas['registry.terraform.io/hashicorp/aws'].resource_schemas;
 if (Object.keys(schema).sort().join() !== inventory.resources.map(r=>r.type).sort().join()) throw Error('Managed schema denominator mismatch');
 return {version:inventory.version, schemaSha256:hash, candidates:Object.fromEntries(inventory.resources.map(r=>[r.type,extract(schema[r.type].block)]))};
}
function render(evidence) {
 if (evidence.version !== inventory.version || evidence.schemaSha256 !== inventory.schemaSha256) throw Error('Stale evidence');
 const rows = new Map(read('docs/resource-support.md').split('\n').filter(l=>l.startsWith('| `aws_')).map(l=> {const c=l.split('|').slice(1,-1).map(x=>x.trim());return [c[0].replace(/`/g,''), c];}));
 if (Object.keys(evidence.candidates).sort().join() !== inventory.resources.map(r=>r.type).sort().join()) throw Error('Evidence inventory mismatch');
 const known = new Set(inventory.resources.map(r=>r.type));
 for (const [type, decision] of Object.entries(decisions.types)) {
  if (!known.has(type)) throw Error('Unknown decision type: '+type);
  if (!['P1', 'P2', 'P3'].includes(decision.priority) || !decision.gap || !decision.status) throw Error('Incomplete decision: '+type);
  if (decision.issue !== undefined && (!Number.isInteger(decision.issue) || decision.issue <= 0)) throw Error('Invalid issue: '+type);
 }
 for (const [type, fields] of Object.entries(evidence.candidates)) {
  if (!Array.isArray(fields) || fields.some(field => typeof field !== 'string' || !/^[a-z0-9_.]+$/.test(field)) || new Set(fields).size !== fields.length) throw Error('Invalid evidence: '+type);
 }
 const out = ['# AWS semantic gap register', '', 'Generated by `node scripts/aws-semantic-audit.cjs`; edit [review decisions](aws-semantic-decisions.json), then regenerate. Method, priorities, representative verification and limitations: [audit guide](aws-semantic-audit.md).', '', `Baseline: AWS Provider ${inventory.version}, commit \`${inventory.commit}\`; ${inventory.resources.length} managed types. Each exact type occurs once, grouped by official service package.`, '', 'Current defaults are copied from the runtime-generated support matrix. **Implemented** below means basic classification/display/scope eligibility only. **Partial** means pre-existing behavior needs the capability-specific limits in the linked guide; it is never a completeness score. **Basic-only** means no dedicated behavior established here. Candidate fields are schema inputs, not verified relationships or a recommendation to expose values.', ''];
 const services = [...new Set(inventory.resources.map(r=>r.service))].sort();
 for (const service of services) {
  out.push('## '+service, '', '| Exact managed type / official contract | Current role; display; scope | Semantic status | Missing capability / disposition | Priority / issue | Schema reference candidates |','| --- | --- | --- | --- | --- | --- |');
  for (const r of inventory.resources.filter(r=>r.service===service)) {
   const row=rows.get(r.type); if (!row) throw Error('Missing matrix row '+r.type);
   const d=decisions.types[r.type] || {};
   const basic=row[5].includes('Basic display only');
   const status=d.status || (basic?'Basic-only':'Partial; consult existing contracts');
   const issue=d.issue;
   const priority=d.priority || 'P3';
   const disposition=d.gap || (basic ? 'Dedicated ownership/network/references not established; defer until an explicit endpoint contract and architecture use case are selected. Keep current default; no automatic card promotion.' : 'Retain existing bounded rules; additional ownership/network/reference candidates require field-level review. Do not reopen completed scope.');
   const candidates=evidence.candidates[r.type];
   out.push(`| [\`${r.type}\`](https://github.com/hashicorp/terraform-provider-aws/blob/${inventory.commit}/${r.documentation}) | ${row[1].split(' / ')[0]}; ${row[2].split(' / ')[0]}; ${row[4]} | ${status} | ${disposition} | ${priority}; ${issue ? '[#'+issue+'](https://github.com/ritz-p/planorama/issues/'+issue+')' : 'Deferred (bounded contract/use case required)'} | ${candidates.length?candidates.map(x=>'\`'+x+'\`').join(', '):'None in conservative candidate scan; not proof of no relationship'} |`);
  }
  out.push('');
 }
 return out.join('\n');
}
if (require.main === module) {
 const args=process.argv.slice(2);
 if (args[0]==='--schema') {
  const data=buildEvidence(fs.readFileSync(args[1]));
  fs.writeFileSync(path.join(root,evidenceFile),JSON.stringify(data,null,2)+'\n');
 } else if (args.length && args[0]!=='--check') throw Error('Usage: node scripts/aws-semantic-audit.cjs [--schema SCHEMA | --check]');
 const output=render(JSON.parse(read(evidenceFile)));
 const dest=path.join(root,'docs/aws-semantic-gaps.md');
 if (args[0]==='--check') {if (read('docs/aws-semantic-gaps.md')!==output) throw Error('Semantic gap register is stale');}
 else fs.writeFileSync(dest,output);
}
module.exports={extract,buildEvidence,render};
